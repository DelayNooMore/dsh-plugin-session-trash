// Build lib/ from src/: remote.js (zod bundled, ESM), index.js + typert.host.js
// copied verbatim, client.js wrapped in the DSH ModuleLoader factory.
//
// The client bundle is built with format=esm (flat output, no lazy __commonJS
// wrappers) and the external namespace imports are rewritten into loader-scope
// require() calls by the transform below. The import shapes are constrained to
// what the transform understands: `import * as X from 'external'` only.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = (name) => path.join(root, 'src', name);
const lib = path.join(root, 'lib');
mkdirSync(lib, { recursive: true });

await build({
  entryPoints: [src('remote.js')],
  outfile: path.join(lib, 'remote.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  logLevel: 'info',
});

copyFileSync(src('index.js'), path.join(lib, 'index.js'));
copyFileSync(src('typert.host.js'), path.join(lib, 'typert.host.js'));

const client = await build({
  entryPoints: [src('client-main.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  external: ['react', 'react-dom', '@deepseek-ai/*'],
  write: false,
  logLevel: 'info',
});
let body = client.outputFiles[0].text;

const externals = new Map();
body = body.replace(/^import\s*\*\s*as\s+(\w+)\s+from\s+["']([^"']+)["'];?\s*$/gm, (m, name, source) => {
  if (!['react', 'react-dom'].includes(source) && !source.startsWith('@deepseek-ai/')) {
    throw new Error(`unexpected external import in bundle output: ${m}`);
  }
  externals.set(name, source);
  return `const ${name} = require(${JSON.stringify(source)});`;
});
body = body.replace(/^export\s*\{[^}]*\};?\s*$/gm, '');
body = body.trimEnd();

if (body.includes('import ') || /(^|\n)export\s/.test(body)) {
  throw new Error('bundle still contains ESM import/export statements after transform');
}

const text = [
  '// Generated by tools/build.mjs — do not edit.',
  `window.__ModuleLoader__.load({id:'dsh-plugin-session-trash',factory:function(require){`,
  `'use strict';`,
  body,
  'return createPlugin();',
  '}});',
  '',
].join('\n');
writeFileSync(path.join(lib, 'client.js'), text);
console.log(`lib/client.js written (${text.length} bytes, externals: ${[...externals].map(([n, s]) => `${n}<-${s}`).join(', ') || 'none'})`);
